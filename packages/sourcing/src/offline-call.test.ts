import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { claimsSoldData } from '@listora/pricing';
import { describe, expect, it } from 'vitest';

import { brandKey } from './brand.ts';
import { scanCall } from './call.ts';
import { BRAND_KEY_SAMPLES, GOLDEN_KIT, OFFLINE_CALL_CASES } from './offline-call.cases.ts';
import { offlineScanCall, tagBrandBucket } from './offline-call.ts';

/**
 * The iPhone's copy of the offline call runs the same golden cases from this JSON file, so the
 * two rules stay equal. After changing a case or the rule, rewrite the file with
 * `UPDATE_IOS_OFFLINE_CALL=1 npx vitest run packages/sourcing/src/offline-call.test.ts`.
 */
const IOS_CASES = fileURLToPath(
  new URL(
    '../../../apps/ios/Packages/Core/Tests/CoreTests/Fixtures/offline-scan-call.json',
    import.meta.url,
  ),
);

function expectedFile(): string {
  const golden = {
    about:
      'Generated by packages/sourcing/src/offline-call.test.ts from offline-call.cases.ts: the offline call golden cases both test suites run. Do not edit.',
    kit: GOLDEN_KIT,
    cases: OFFLINE_CALL_CASES,
    brandKeys: BRAND_KEY_SAMPLES.map((brand) => ({ brand, key: brandKey(brand) ?? null })),
  };
  return `${JSON.stringify(golden, null, 2)}\n`;
}

describe('offlineScanCall', () => {
  it.each(OFFLINE_CALL_CASES)('$name', ({ tagText, read }) => {
    expect(offlineScanCall(GOLDEN_KIT, tagText) ?? null).toEqual(read);
  });

  it("makes the server's call on the same sales: a sure brand read, no category, no flags", () => {
    for (const { tagText, read } of OFFLINE_CALL_CASES) {
      const bucket = tagBrandBucket(GOLDEN_KIT, tagText);
      if (read === null || bucket === undefined) continue;
      const sales = bucket.forCall;
      const low = sales?.low.amountCents ?? 0;
      const high = sales?.high.amountCents ?? 0;
      const payouts = new Map([
        [low, sales?.conservativePayout.amountCents ?? 0],
        [high, sales?.optimisticPayout.amountCents ?? 0],
      ]);
      const server = scanCall({
        identityConfidence: 1,
        ownHistory:
          sales === undefined
            ? undefined
            : {
                level: 'brand',
                saleIds: [],
                prices: {
                  count: sales.soldCount,
                  lowCents: low,
                  medianCents: low,
                  highCents: high,
                },
              },
        flags: { visibleDamage: false, lotOrBundle: false, counterfeitProne: false },
        fees: (price) => price - (payouts.get(price) ?? price),
      });
      expect([server.call, server.confidence, server.basis], tagText.join(' / ')).toEqual([
        read.call,
        read.confidence,
        read.basis,
      ]);
      expect(server.conservativePayoutCents).toBe(read.conservativePayoutCents);
      expect(server.optimisticPayoutCents).toBe(read.optimisticPayoutCents);
    }
  });

  it('never claims sold data the household does not have', () => {
    for (const { read } of OFFLINE_CALL_CASES) {
      if (read !== null && read.basis === 'none') expect(claimsSoldData(read.basedOn)).toBe(false);
    }
  });

  it('ignores a kit of a format it does not know', () => {
    expect(offlineScanCall({ ...GOLDEN_KIT, version: 1 }, ['LULULEMON'])).toBeUndefined();
  });

  it("matches the iPhone's copy of the golden cases", async () => {
    const expected = expectedFile();
    if (process.env['UPDATE_IOS_OFFLINE_CALL'] === '1') await writeFile(IOS_CASES, expected);
    expect(await readFile(IOS_CASES, 'utf8')).toBe(expected);
  });
});

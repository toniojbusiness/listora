/** Rows of booleans (true = ink), always GLYPH_HEIGHT rows of GLYPH_WIDTH columns. */
export type Bitmap = readonly (readonly boolean[])[];

const BITMAPS = new Map<string, Bitmap>(
  Object.entries(GLYPHS).map(([char, rows]) => {
    const parsed = rows.split(' ').map((row) => Array.from(row, (cell) => cell === '#'));
    while (parsed.length < GLYPH_HEIGHT) parsed.push(Array<boolean>(GLYPH_WIDTH).fill(false));
    return [char, parsed];
  }),
);

export const FONT_CHARACTERS: readonly string[] = [...BITMAPS.keys()];

export function glyph(char: string): Bitmap {
  const bitmap = BITMAPS.get(char);
  if (bitmap === undefined) {
    throw new RangeError(`The corpus font has no glyph for ${JSON.stringify(char)}`);
  }
  return bitmap;
}

/** The raw glyph rows, for the font's own consistency test. */
export function glyphSource(char: string): string | undefined {
  return GLYPHS[char];
}

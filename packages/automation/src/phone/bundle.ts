/**
 * Builds the phone runtime bundle the iPhone app ships (docs/features/phone-execution.md): one
 * script, `listoraPhone`, holding the phone runtime and everything it runs (the marketplace
 * scripts, the shared session rules, the page functions), from this package's own source. The
 * app runs it in a hidden web view; it is committed as an app resource, and `bundle.test.ts`
 * fails when it no longer matches the source. Rewrite it with `npm run phone:bundle`.
 *
 * The bundle must hold only code that runs in a web page: modules are treated as free of side
 * effects, so a module the runtime imports for a type or two brings nothing else along, and a
 * build that still needs Node (an import left external) fails.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { rolldown } from 'rolldown';

import { PHONE_BUNDLE_PATH } from './bundle-file.ts';

export { PHONE_BUNDLE_PATH };

const PACKAGE_DIR = fileURLToPath(new URL('../../', import.meta.url));
const ENTRY = fileURLToPath(new URL('./bundle-entry.ts', import.meta.url));

const HEADER = `// The Listora phone runtime (docs/features/phone-execution.md). Generated by
// \`npm run phone:bundle\` from packages/automation/src/phone/bundle-entry.ts; do not edit.
`;

export async function buildPhoneBundle(): Promise<string> {
  const bundle = await rolldown({
    input: ENTRY,
    cwd: PACKAGE_DIR,
    platform: 'browser',
    treeshake: { moduleSideEffects: false },
    // Modules the runtime never uses still resolve (Node's own among them); none may be kept.
    logLevel: 'silent',
  });
  try {
    const { output } = await bundle.generate({ format: 'iife', minify: false });
    const [chunk, ...rest] = output;
    if (rest.length > 0) {
      throw new Error('the phone bundle must be one script');
    }
    if (chunk.imports.length > 0) {
      throw new Error(
        `the phone bundle needs modules a web page lacks: ${chunk.imports.join(', ')}`,
      );
    }
    return `${HEADER}${chunk.code}`;
  } finally {
    await bundle.close();
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(PHONE_BUNDLE_PATH, await buildPhoneBundle());
  process.stdout.write(`wrote ${PHONE_BUNDLE_PATH}\n`);
}
